"""Validate structural and semantic invariants of an MQT LLM JSON dataset."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Any

from qiskit import QuantumCircuit
from qiskit.qasm2 import loads as qasm2_loads


EXPECTED_SCHEMA_VERSION = "1.0.0"
EXPECTED_FEATURE_COUNT = 49


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dataset", type=Path, help="Dataset JSON generated by script 07.")
    return parser.parse_args()


def reject_nonstandard_number(value: str) -> Any:
    """Reject NaN and Infinity, which are not valid standard JSON numbers."""
    raise ValueError(f"Non-standard JSON number: {value}")


def sha256_text(value: str) -> str:
    """Return the SHA-256 digest of UTF-8 text."""
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def require(condition: bool, message: str, errors: list[str]) -> None:
    """Collect a validation error when a condition is false."""
    if not condition:
        errors.append(message)


def validate_record(
    record: dict[str, Any],
    *,
    hardware_catalog: dict[str, Any],
    feature_names: list[str],
) -> list[str]:
    """Validate one end-to-end record."""
    errors: list[str] = []
    prefix = f"record {record.get('record_id', '<missing>')}"

    require(record.get("status") in {"success", "error", "timeout"}, f"{prefix}: invalid status", errors)
    require(isinstance(record.get("total_elapsed_seconds"), (int, float)), f"{prefix}: missing elapsed time", errors)

    source = record.get("source_circuit") or {}
    source_qasm = source.get("qasm2")
    require(isinstance(source_qasm, str), f"{prefix}: missing source QASM", errors)
    if isinstance(source_qasm, str):
        require(
            source.get("sha256") == sha256_text(source_qasm),
            f"{prefix}: source QASM SHA-256 mismatch",
            errors,
        )
        try:
            source_circuit: QuantumCircuit = qasm2_loads(source_qasm)
        except Exception as error:  # noqa: BLE001 - report all malformed records
            errors.append(f"{prefix}: source QASM is not parseable: {type(error).__name__}: {error}")
        else:
            require(
                source_circuit.num_qubits == source.get("summary", {}).get("num_qubits"),
                f"{prefix}: source qubit count does not match its summary",
                errors,
            )

    features = record.get("feature_vector") or {}
    require(features.get("feature_count") == EXPECTED_FEATURE_COUNT, f"{prefix}: feature count is not 49", errors)
    require(features.get("ordered_names") == feature_names, f"{prefix}: feature names differ from schema", errors)
    require(
        len(features.get("ordered_values", [])) == EXPECTED_FEATURE_COUNT,
        f"{prefix}: feature-value length is not 49",
        errors,
    )
    require(
        set(features.get("by_name", {})) == set(feature_names),
        f"{prefix}: feature dictionary keys differ from schema",
        errors,
    )

    selection = record.get("device_selection")
    if selection is not None:
        selected_device = selection.get("selected_device")
        require(selected_device in hardware_catalog, f"{prefix}: selected device is absent from hardware catalog", errors)
        ranking_names = [row.get("device") for row in selection.get("ranking", [])]
        require(selected_device in ranking_names, f"{prefix}: selected device is absent from ranking", errors)

    if record.get("status") == "success":
        require(record.get("error") is None, f"{prefix}: successful record contains an error", errors)
        compilation = record.get("compilation") or {}
        compiled = record.get("compiled_circuit") or {}
        steps = compilation.get("steps", [])
        pass_names = compilation.get("selected_pass_names", [])
        require(compilation.get("step_count") == len(steps), f"{prefix}: step count mismatch", errors)
        require(len(pass_names) == len(steps), f"{prefix}: selected-pass count mismatch", errors)
        require(bool(pass_names) and pass_names[-1] == "terminate", f"{prefix}: trace does not end in terminate", errors)
        require(
            all(step.get("selected_action", {}).get("name") == name for step, name in zip(steps, pass_names, strict=True)),
            f"{prefix}: selected pass list differs from step trace",
            errors,
        )

        compiled_qasm = compiled.get("qasm2")
        require(isinstance(compiled_qasm, str), f"{prefix}: missing compiled QASM", errors)
        if isinstance(compiled_qasm, str):
            require(
                compiled.get("sha256") == sha256_text(compiled_qasm),
                f"{prefix}: compiled QASM SHA-256 mismatch",
                errors,
            )
            try:
                compiled_circuit: QuantumCircuit = qasm2_loads(compiled_qasm)
            except Exception as error:  # noqa: BLE001 - report all malformed records
                errors.append(f"{prefix}: compiled QASM is not parseable: {type(error).__name__}: {error}")
            else:
                require(
                    compiled_circuit.depth() == compiled.get("summary", {}).get("depth"),
                    f"{prefix}: compiled depth does not match its summary",
                    errors,
                )

        environment_reward = compilation.get("terminal_reward_returned_by_environment")
        recomputed_score = compilation.get("final_score_recomputed")
        if isinstance(environment_reward, (int, float)) and isinstance(recomputed_score, (int, float)):
            require(
                math.isclose(environment_reward, recomputed_score, rel_tol=1e-12, abs_tol=1e-12),
                f"{prefix}: terminal reward differs from recomputed score",
                errors,
            )
    else:
        require(isinstance(record.get("error"), dict), f"{prefix}: failed record has no structured error", errors)

    return errors


def main() -> int:
    """Validate a JSON dataset and print a compact report."""
    args = parse_args()
    payload = json.loads(
        args.dataset.read_text(encoding="utf-8"),
        parse_constant=reject_nonstandard_number,
    )
    errors: list[str] = []

    require(payload.get("schema_version") == EXPECTED_SCHEMA_VERSION, "unexpected schema version", errors)
    records = payload.get("records")
    require(isinstance(records, list), "records must be a list", errors)
    if not isinstance(records, list):
        records = []

    dataset = payload.get("dataset") or {}
    require(dataset.get("record_count") == len(records), "top-level record count mismatch", errors)
    require(
        dataset.get("successful_records") == sum(record.get("status") == "success" for record in records),
        "top-level success count mismatch",
        errors,
    )
    require(
        dataset.get("failed_records") == sum(record.get("status") == "error" for record in records),
        "top-level error count mismatch",
        errors,
    )
    require(
        dataset.get("timeout_records") == sum(record.get("status") == "timeout" for record in records),
        "top-level timeout count mismatch",
        errors,
    )

    feature_schema = payload.get("feature_schema") or {}
    feature_names = feature_schema.get("ordered_names", [])
    require(feature_schema.get("feature_count") == EXPECTED_FEATURE_COUNT, "feature schema count is not 49", errors)
    require(len(feature_names) == EXPECTED_FEATURE_COUNT, "feature schema name count is not 49", errors)
    require(len(set(feature_names)) == len(feature_names), "feature schema contains duplicate names", errors)

    record_ids = [record.get("record_id") for record in records]
    require(len(record_ids) == len(set(record_ids)), "record IDs are not unique", errors)

    hardware_catalog = payload.get("hardware_catalog") or {}
    for record in records:
        errors.extend(
            validate_record(
                record,
                hardware_catalog=hardware_catalog,
                feature_names=feature_names,
            )
        )

    if errors:
        print(f"INVALID: {len(errors)} problem(s)")
        for error in errors:
            print(f"- {error}")
        return 1

    print(
        "VALID: "
        f"records={len(records)} "
        f"success={dataset.get('successful_records')} "
        f"errors={dataset.get('failed_records')} "
        f"timeouts={dataset.get('timeout_records')} "
        f"devices={len(hardware_catalog)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
